"""Game Logic Generation (Phase 23.5-7): CreativeSkill blueprints.

The layer ordinary image tools do not have — the system generates *game
logic*, not just pictures:

    goal ("给机械猫增加一个冲刺技能")
      -> Skill Blueprint (CreativeSkill protocol)
           {name, trigger{cooldown}, animation, damage, effect, engine}
      -> Engine Script (Cocos event bindings + Unity C# component)
      -> Playable Skill (after the Simulation Agent's balance pass)

Everything is deterministic: the skill type / element tables below are the
frozen interface a trained Logic Model plugs into.
"""

import re
from typing import Any

SKILL_TYPES: dict[str, dict[str, Any]] = {
    "dash": {
        "keywords": ("冲刺", "疾跑", "dash"),
        "damage": 20,
        "cooldown": 3.0,
        "animation": "dash_attack",
        "movement": {"distance": 240, "duration": 0.25},
    },
    "fireball": {
        "keywords": ("火球", "fireball"),
        "damage": 35,
        "cooldown": 2.5,
        "animation": "cast_attack",
        "projectile": {"speed": 320},
    },
    "heal": {
        "keywords": ("治疗", "回复", "heal"),
        "damage": 0,
        "cooldown": 8.0,
        "animation": "cast_buff",
        "heal": 30,
    },
    "shield": {
        "keywords": ("护盾", "格挡", "shield"),
        "damage": 0,
        "cooldown": 10.0,
        "animation": "cast_guard",
        "guard": {"duration": 3.0},
    },
}

ELEMENTS: dict[str, dict[str, Any]] = {
    "fire": {"keywords": ("火", "焰", "fire"), "multiplier": 2.5, "effect": "fire_burst"},
    "ice": {"keywords": ("冰", "ice"), "multiplier": 1.2, "effect": "ice_shatter"},
    "lightning": {"keywords": ("雷", "电", "lightning", "thunder"), "multiplier": 1.8, "effect": "lightning_arc"},
}
DEFAULT_EFFECT = "blue_flash"

DAMAGE_RANGE = (5.0, 80.0)
DASH_DISTANCE_RANGE = (40.0, 400.0)


def detect_element(goal: str) -> str | None:
    lowered = (goal or "").lower()
    return next(
        (name for name, spec in ELEMENTS.items() if any(k in lowered for k in spec["keywords"])),
        None,
    )


def detect_skill_type(goal: str) -> str:
    lowered = (goal or "").lower()
    return next(
        (name for name, spec in SKILL_TYPES.items() if any(k in lowered for k in spec["keywords"])),
        "custom_strike",
    )


def build_skill_blueprint(goal: str, character_name: str) -> dict[str, Any]:
    """Goal -> CreativeSkill blueprint (deterministic numbers)."""
    lowered = (goal or "").lower()
    skill_type = detect_skill_type(goal)
    spec = SKILL_TYPES.get(skill_type) or {
        "damage": 25,
        "cooldown": 4.0,
        "animation": "custom_attack",
    }
    element = detect_element(goal)
    multiplier = ELEMENTS[element]["multiplier"] if element else 1.0
    effect = ELEMENTS[element]["effect"] if element else DEFAULT_EFFECT

    name = skill_type if (element and element in skill_type) else (
        f"{element}_{skill_type}" if element else skill_type
    )
    damage = round(float(spec["damage"]) * multiplier, 1)
    cooldown = float(spec["cooldown"])

    blueprint: dict[str, Any] = {
        "name": name,
        "type": skill_type,
        "character": character_name,
        "trigger": {"input": _input_binding(skill_type), "cooldown": cooldown},
        "animation": spec["animation"],
        "damage": damage,
        "effect": effect,
        "element": element,
        "version": "v1",
    }
    for extra_key in ("movement", "projectile", "heal", "guard"):
        if extra_key in spec:
            blueprint[extra_key] = spec[extra_key]
    return blueprint


def _input_binding(skill_type: str) -> str:
    return {
        "dash": "key_shift",
        "fireball": "key_q",
        "heal": "key_e",
        "shield": "key_f",
    }.get(skill_type, "key_j")


def pascal(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^0-9a-zA-Z]+", name) if p)


def engine_scripts(blueprint: dict[str, Any]) -> dict[str, Any]:
    """Blueprint -> engine bindings: Cocos animation events + Unity C#."""
    name = blueprint["name"]
    cls = pascal(name)
    cocos = {
        "component": f"{cls}Skill",
        "events": [
            {
                "clip": blueprint["animation"],
                "frame": 2,
                "handler": f"on_{name}",
                "params": {
                    "damage": blueprint["damage"],
                    "effect": blueprint["effect"],
                },
            }
        ],
    }
    unity = {
        "script": f"Assets/Scripts/Skills/{cls}Skill.cs",
        "code": (
            "// Auto-generated by CreativeForge GameLogicAgent (Phase 23)\n"
            f"public class {cls}Skill : MonoBehaviour {{\n"
            f"    public float cooldown = {blueprint['trigger']['cooldown']}f;\n"
            f"    public int damage = {int(blueprint['damage'])};\n"
            f"    public string effect = \"{blueprint['effect']}\";\n\n"
            f"    void Start() {{ /* bind animation event: {blueprint['animation']} */ }}\n"
            f"    public void Trigger() {{ /* {blueprint['effect']} VFX + hitbox window */ }}\n"
            "}"
        ),
    }
    return {"cocos": cocos, "unity": unity}
